"""Optional lockfile for ckdn.toml governance (CI / review).

The lock pins everything that decides what a check runs and how its result is
judged: each atomic check's command, parser, parser options, env and timeout;
each alias's members; and the ``[run]`` settings that govern safety and the
gate (``command_policy``, ``command_allowlist``, ``baseline``, ``runs_dir``).
Pinning the command alone let a reviewed lock wave through a removed
``fail_under`` or a ``command_policy = "off"``.

Each atomic entry keeps ``command_sha256`` next to the full ``check_sha256``:
older ckdn reads only the former, so one lock file serves both. A lock written
before the full digest existed (no ``[run]`` table) still verifies its
commands; :func:`lock_warnings` says it covers nothing else. Transitional:
make those gaps errors once old locks have had time to be regenerated.
"""

from __future__ import annotations

import hashlib
import json
import re
import tomllib
from pathlib import Path
from typing import Any

from ckdn.config import CheckConfig, Config

LOCK_NAME = "ckdn.lock.toml"
_POLICY_PROBE = "_ckdn_policy_probe"
_BARE_KEY = re.compile(r"^[A-Za-z0-9_-]+$")


def command_digest(command: str) -> str:
    return hashlib.sha256(command.encode("utf-8")).hexdigest()


def _canonical_digest(doc: dict[str, Any]) -> str:
    # `default=str` covers TOML dates and times; everything else is JSON.
    blob = json.dumps(
        doc, sort_keys=True, separators=(",", ":"), ensure_ascii=False, default=str
    )
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()


def check_digest(check: CheckConfig) -> str:
    """SHA-256 over a check's whole definition, not just its command."""
    if check.is_alias:
        return _canonical_digest(
            {"members": list(check.members or ()), "fail_fast": check.fail_fast}
        )
    return _canonical_digest(
        {
            "command": check.command,
            "parser": check.parser,
            "timeout": check.timeout,
            "env": check.env,
            "options": check.options,
        }
    )


def run_settings_digest(cfg: Config) -> str:
    """SHA-256 over the ``[run]`` settings that govern safety and the gate."""
    run = cfg.run
    return _canonical_digest(
        {
            "command_policy": run.command_policy,
            "command_allowlist": (
                None if run.command_allowlist is None else list(run.command_allowlist)
            ),
            "baseline": None if run.baseline is None else run.baseline.as_posix(),
            "runs_dir": run.runs_dir.as_posix(),
        }
    )


def _toml_key(name: str) -> str:
    """A check name as a TOML key: bare when it can be, quoted otherwise.

    Written bare, ``py.test`` read back as a ``py`` table holding ``test``,
    so the entry could never be found again.
    """
    return name if _BARE_KEY.match(name) else json.dumps(name, ensure_ascii=False)


def default_lock_path(cfg: Config) -> Path:
    return cfg.config_path.parent / LOCK_NAME


def write_config_lock(cfg: Config, path: Path | None = None) -> Path:
    """Write ``ckdn.lock.toml`` pinning every check and the ``[run]`` policy."""
    target = path or default_lock_path(cfg)
    sections = [
        "# Generated by `ckdn lock-config`. Commit it, and run\n"
        "# `ckdn verify-config --locked` in CI to catch unreviewed config changes.\n"
        f"# Source: {cfg.config_path.name}\n",
        f'[run]\nsettings_sha256 = "{run_settings_digest(cfg)}"\n',
    ]
    for name in sorted(cfg.checks):
        check = cfg.checks[name]
        section = f"[check.{_toml_key(name)}]\n"
        if check.command is not None:
            section += f'command_sha256 = "{command_digest(check.command)}"\n'
        sections.append(section + f'check_sha256 = "{check_digest(check)}"\n')
    # One blank line between sections and none at the end, so the file is
    # stable under end-of-file fixers.
    target.write_text("\n".join(sections), encoding="utf-8")
    return target


def _verify_command(name: str, check: CheckConfig, entry: dict[str, Any]) -> str | None:
    expected = entry.get("command_sha256")
    if not isinstance(expected, str) or not expected:
        return f"[check.{name}] missing command_sha256 in lock file"
    actual = command_digest(check.command or "")
    if actual != expected:
        return (
            f"[check.{name}] command changed since lock "
            f"(expected {expected[:12]}…, got {actual[:12]}…)"
        )
    return None


def _verify_check(
    name: str, check: CheckConfig, entry: dict[str, Any], *, full: bool
) -> str | None:
    """One lock entry against its check; ``full`` once the lock pins more."""
    if not check.is_alias:
        error = _verify_command(name, check, entry)
        if error is not None:
            return error
    expected = entry.get("check_sha256")
    if expected is None and not full:
        return None  # a command-only lock: lock_warnings says so
    if not isinstance(expected, str) or not expected:
        return f"[check.{name}] missing check_sha256 in lock file"
    if check_digest(check) != expected:
        what = (
            "members or fail_fast"
            if check.is_alias
            else "parser, options, env or timeout"
        )
        return f"[check.{name}] {what} changed since lock"
    return None


def _load_lock(lock_path: Path) -> tuple[dict[str, Any] | None, list[str]]:
    if not lock_path.exists():
        return None, [f"lock file not found: {lock_path} (run `ckdn lock-config`)"]
    try:
        data = tomllib.loads(lock_path.read_text(encoding="utf-8"))
    except tomllib.TOMLDecodeError as exc:
        return None, [f"invalid TOML in {lock_path}: {exc}"]
    if not isinstance(data.get("check", {}), dict):
        return None, [f"{lock_path}: missing [check.<name>] tables"]
    return data, []


def _is_full_lock(data: dict[str, Any]) -> bool:
    return isinstance(data.get("run"), dict)


def verify_config_lock(
    cfg: Config,
    path: Path | None = None,
) -> list[str]:
    """Compare the config against a lock file. Returns error strings."""
    lock_path = path or default_lock_path(cfg)
    data, errors = _load_lock(lock_path)
    if data is None:
        return errors
    locked: dict[str, Any] = data.get("check", {})
    full = _is_full_lock(data)

    if full:
        expected = data["run"].get("settings_sha256")
        if not isinstance(expected, str) or not expected:
            errors.append("[run] missing settings_sha256 in lock file")
        elif run_settings_digest(cfg) != expected:
            errors.append(
                "[run] command_policy, command_allowlist, baseline or runs_dir "
                "changed since lock"
            )

    for name, check in sorted(cfg.checks.items()):
        entry = locked.get(name)
        if not isinstance(entry, dict):
            # A command-only lock never listed aliases; lock_warnings covers it.
            if not check.is_alias or full:
                errors.append(f"[check.{name}] missing from {lock_path.name}")
            continue
        error = _verify_check(name, check, entry, full=full)
        if error is not None:
            errors.append(error)

    errors.extend(
        f"[check.{name}] present in lock file but not in config"
        for name in sorted(locked)
        if name not in cfg.checks
    )
    return errors


def lock_warnings(cfg: Config, path: Path | None = None) -> list[str]:
    """Say when a lock verifies commands only (written by an older ckdn)."""
    data, _errors = _load_lock(path or default_lock_path(cfg))
    if data is None or _is_full_lock(data):
        return []
    return [
        "the lock file pins commands only (written by an older ckdn): parsers, "
        "options, env, timeouts, aliases and [run] policy can change unnoticed; "
        "run `ckdn lock-config` and commit the result"
    ]


def verify_config(
    cfg: Config,
    *,
    locked: bool = False,
    lock_path: Path | None = None,
) -> list[str]:
    """Validate command policy and optionally the lock file. Returns error strings."""
    from ckdn.command_policy import CommandPolicyError, validate_command
    from ckdn.runner import build_tokens

    errors: list[str] = []
    probe_dir = cfg.cwd / _POLICY_PROBE

    for name in sorted(cfg.checks):
        check = cfg.checks[name]
        if check.is_alias or check.command is None:
            continue
        try:
            tokens = build_tokens(check.command, probe_dir, [])
            validate_command(
                check.command,
                cwd=cfg.cwd,
                policy=cfg.run.command_policy,
                allowlist_prefixes=cfg.run.command_allowlist,
                tokens=tokens,
                env=check.env,
            )
        except CommandPolicyError as exc:
            errors.append(f"[check.{name}] {exc}")

    if locked:
        errors.extend(verify_config_lock(cfg, lock_path))
    return errors
